-- Order tracking, status history, invoices, secure invoice sharing and order notifications.
-- Run after supabase/schema.sql (new database) or after the other migrations (existing database).
-- Safe to run more than once.
begin;

-- Helper used by RLS policies. SECURITY DEFINER avoids recursive policy evaluation on profiles.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin');
$$;

-- 1. Orders: richer status set, payment state and invoice breakdown fields.
alter table public.orders drop constraint if exists orders_status_check;
alter table public.orders
  add constraint orders_status_check
  check (status in ('pending', 'confirmed', 'processing', 'fulfilled', 'cancelled', 'returned'));

alter table public.orders add column if not exists amount_paid integer not null default 0 check (amount_paid >= 0);
alter table public.orders add column if not exists payment_status text not null default 'unpaid';
alter table public.orders drop constraint if exists orders_payment_status_check;
alter table public.orders
  add constraint orders_payment_status_check
  check (payment_status in ('unpaid', 'partial', 'paid', 'refunded'));
alter table public.orders add column if not exists estimated_delivery date;
alter table public.orders add column if not exists delivery_fee integer check (delivery_fee is null or delivery_fee >= 0);
alter table public.orders add column if not exists discount_amount integer not null default 0 check (discount_amount >= 0);
alter table public.orders add column if not exists tax_amount integer not null default 0 check (tax_amount >= 0);

-- Backfill payment state for orders that Monime already confirmed.
update public.orders
set amount_paid = payment_due
where amount_paid = 0
  and payment_method = 'monime'
  and status in ('confirmed', 'fulfilled')
  and payment_due > 0;

update public.orders
set payment_status = case
  when total > 0 and amount_paid >= total then 'paid'
  when amount_paid > 0 then 'partial'
  else 'unpaid'
end
where payment_status <> 'refunded';

-- 2. Status history, invoices, share links and notifications.
create table if not exists public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  status text not null check (status in ('pending', 'confirmed', 'processing', 'fulfilled', 'cancelled', 'returned')),
  previous_status text,
  note text check (note is null or char_length(note) <= 500),
  changed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists order_status_history_order_idx
  on public.order_status_history (order_id, created_at, id);

create sequence if not exists public.invoice_number_seq;

create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  invoice_number text not null unique,
  issued_at timestamptz not null default now(),
  paid_at timestamptz
);

-- Only a SHA-256 hash of each share token is stored, so a database leak cannot reveal usable links.
create table if not exists public.invoice_share_links (
  id uuid primary key default gen_random_uuid(),
  invoice_id bigint not null references public.invoices(id) on delete cascade,
  token_hash text not null unique,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz,
  last_accessed_at timestamptz,
  access_count integer not null default 0,
  constraint share_link_expiry_after_creation check (expires_at > created_at)
);
create index if not exists invoice_share_links_invoice_idx on public.invoice_share_links (invoice_id);

create table if not exists public.order_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  order_id bigint not null references public.orders(id) on delete cascade,
  kind text not null check (kind in ('order_confirmed', 'order_processed')),
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  -- One notification per order and event: repeated status writes can never duplicate it.
  constraint order_notifications_once unique (order_id, kind)
);
create index if not exists order_notifications_user_idx
  on public.order_notifications (user_id, read_at, created_at desc);

-- 3. Server-side status transition validation (applies to every writer, including webhooks).
create or replace function public.order_status_transition_allowed(old_status text, new_status text)
returns boolean
language sql
immutable
as $$
  select case old_status
    when 'pending' then new_status in ('confirmed', 'cancelled')
    when 'confirmed' then new_status in ('processing', 'fulfilled', 'cancelled')
    when 'processing' then new_status in ('fulfilled', 'cancelled')
    when 'fulfilled' then new_status in ('returned')
    else false
  end;
$$;

create or replace function public.orders_before_update_guard()
returns trigger
language plpgsql
as $$
begin
  if new.status is distinct from old.status
     and not public.order_status_transition_allowed(old.status, new.status) then
    raise exception 'Invalid order status transition: % -> %', old.status, new.status
      using errcode = 'check_violation';
  end if;

  -- Payment state is always derived from the recorded amount; 'refunded' is an explicit admin decision.
  if new.payment_status <> 'refunded' then
    new.payment_status := case
      when new.total > 0 and new.amount_paid >= new.total then 'paid'
      when new.amount_paid > 0 then 'partial'
      else 'unpaid'
    end;
  end if;
  return new;
end;
$$;

drop trigger if exists orders_before_update_guard on public.orders;
create trigger orders_before_update_guard
before update on public.orders
for each row execute function public.orders_before_update_guard();

-- 4. History, invoice and notification side effects.
create or replace function public.orders_after_change()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  v_note text := nullif(trim(coalesce(current_setting('app.order_note', true), '')), '');
  v_actor uuid := nullif(current_setting('app.order_actor', true), '')::uuid;
begin
  if tg_op = 'INSERT' then
    insert into public.order_status_history (order_id, status, previous_status, note)
    values (new.id, new.status, null, 'Order placed');
    insert into public.invoices (order_id, invoice_number)
    values (new.id, 'INV-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('public.invoice_number_seq')::text, 6, '0'))
    on conflict (order_id) do nothing;
  elsif new.status is distinct from old.status then
    insert into public.order_status_history (order_id, status, previous_status, note, changed_by)
    values (new.id, new.status, old.status, v_note, v_actor);
  end if;

  if new.user_id is not null and (tg_op = 'INSERT' or new.status is distinct from old.status) then
    if new.status = 'confirmed' then
      insert into public.order_notifications (user_id, order_id, kind, message)
      values (new.user_id, new.id, 'order_confirmed', 'Your order #' || new.id || ' has been confirmed.')
      on conflict (order_id, kind) do nothing;
    elsif new.status = 'processing' then
      insert into public.order_notifications (user_id, order_id, kind, message)
      values (new.user_id, new.id, 'order_processed', 'Your order #' || new.id || ' is being processed.')
      on conflict (order_id, kind) do nothing;
    end if;
  end if;

  if new.payment_status = 'paid' then
    update public.invoices set paid_at = coalesce(paid_at, now()) where order_id = new.id;
  end if;
  return null;
end;
$$;

drop trigger if exists orders_after_change on public.orders;
create trigger orders_after_change
after insert or update of status, payment_status, amount_paid on public.orders
for each row execute function public.orders_after_change();

-- Backfill history and invoices for orders that existed before this migration.
insert into public.order_status_history (order_id, status, previous_status, note, created_at)
select o.id, 'pending', null, 'Order placed', o.created_at
from public.orders o
where not exists (select 1 from public.order_status_history h where h.order_id = o.id);

insert into public.order_status_history (order_id, status, previous_status, note, created_at)
select o.id, o.status, 'pending', null, o.updated_at
from public.orders o
where o.status <> 'pending'
  and not exists (
    select 1 from public.order_status_history h where h.order_id = o.id and h.status = o.status
  );

insert into public.invoices (order_id, invoice_number, issued_at, paid_at)
select o.id,
       'INV-' || to_char(o.created_at, 'YYYY') || '-' || lpad(nextval('public.invoice_number_seq')::text, 6, '0'),
       o.created_at,
       case when o.payment_status = 'paid' then o.updated_at end
from public.orders o
where not exists (select 1 from public.invoices i where i.order_id = o.id)
order by o.created_at, o.id;

-- 5. Admin-only order update: validates, records notes/history and payment in one transaction.
create or replace function public.admin_update_order(
  p_order_id bigint,
  p_actor uuid,
  p_status text default null,
  p_note text default null,
  p_estimated_delivery date default null,
  p_clear_estimate boolean default false,
  p_payment_status text default null
)
returns public.orders
language plpgsql
security definer set search_path = public
as $$
declare
  v_order public.orders;
  v_note text := nullif(trim(coalesce(p_note, '')), '');
  v_status_changed boolean;
  v_payment_changed boolean := false;
begin
  if not exists (select 1 from public.profiles where id = p_actor and role = 'admin') then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if v_note is not null and char_length(v_note) > 500 then
    raise exception 'Note is too long' using errcode = 'check_violation';
  end if;
  if p_status is not null and p_status not in ('pending', 'confirmed', 'processing', 'fulfilled', 'cancelled', 'returned') then
    raise exception 'Invalid status' using errcode = 'check_violation';
  end if;
  if p_payment_status is not null and p_payment_status not in ('paid', 'refunded') then
    raise exception 'Invalid payment status' using errcode = 'check_violation';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order not found' using errcode = 'no_data_found';
  end if;

  v_status_changed := p_status is not null and p_status <> v_order.status;
  perform set_config('app.order_note', coalesce(v_note, ''), true);
  perform set_config('app.order_actor', p_actor::text, true);

  if p_payment_status = 'paid' then
    if coalesce(p_status, v_order.status) in ('cancelled', 'returned') then
      raise exception 'Cannot mark a cancelled or returned order as paid' using errcode = 'check_violation';
    end if;
    v_payment_changed := v_order.payment_status <> 'paid';
  elsif p_payment_status = 'refunded' then
    if v_order.amount_paid <= 0 then
      raise exception 'Nothing to refund' using errcode = 'check_violation';
    end if;
    v_payment_changed := v_order.payment_status <> 'refunded';
  end if;

  update public.orders
  set status = coalesce(p_status, status),
      estimated_delivery = case
        when p_clear_estimate then null
        when p_estimated_delivery is not null then p_estimated_delivery
        else estimated_delivery
      end,
      amount_paid = case when p_payment_status = 'paid' then total else amount_paid end,
      payment_status = case
        when p_payment_status = 'refunded' then 'refunded'
        when p_payment_status = 'paid' then 'paid'
        else payment_status
      end
  where id = p_order_id
  returning * into v_order;

  -- Notes or payment changes without a status change are still part of the history.
  if not v_status_changed and (v_note is not null or v_payment_changed) then
    insert into public.order_status_history (order_id, status, previous_status, note, changed_by)
    values (
      p_order_id, v_order.status, v_order.status,
      coalesce(v_note, 'Payment marked ' || v_order.payment_status),
      p_actor
    );
  end if;

  return v_order;
end;
$$;

revoke all on function public.admin_update_order(bigint, uuid, text, text, date, boolean, text) from public, anon, authenticated;
grant execute on function public.admin_update_order(bigint, uuid, text, text, date, boolean, text) to service_role;

-- 6. Row level security: customers only reach their own rows; writes go through the server.
alter table public.order_status_history enable row level security;
alter table public.invoices enable row level security;
alter table public.invoice_share_links enable row level security;
alter table public.order_notifications enable row level security;

-- Guest orders (user_id is null) are no longer readable, and clients can no longer insert
-- orders directly; the API inserts with the server-side secret key after validating prices.
drop policy if exists "Users can view their own orders" on public.orders;
create policy "Users can view their own orders"
on public.orders for select
using (auth.uid() = user_id);

drop policy if exists "Users can create their own orders" on public.orders;

drop policy if exists "Users can view their own order history" on public.order_status_history;
create policy "Users can view their own order history"
on public.order_status_history for select
using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));

drop policy if exists "Admins can view all order history" on public.order_status_history;
create policy "Admins can view all order history"
on public.order_status_history for select
using (public.is_admin());

drop policy if exists "Users can view their own invoices" on public.invoices;
create policy "Users can view their own invoices"
on public.invoices for select
using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));

drop policy if exists "Admins can view all invoices" on public.invoices;
create policy "Admins can view all invoices"
on public.invoices for select
using (public.is_admin());

drop policy if exists "Users can view their own notifications" on public.order_notifications;
create policy "Users can view their own notifications"
on public.order_notifications for select
using (auth.uid() = user_id);

-- invoice_share_links intentionally has no client policies: only the server (secret key) can read it.

commit;
