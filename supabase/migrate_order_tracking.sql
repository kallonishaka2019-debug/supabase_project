begin;

alter table public.orders
  drop constraint if exists orders_status_check;

update public.orders
set status = 'delivered'
where status = 'fulfilled';

alter table public.orders
  add constraint orders_status_check
  check (status in (
    'pending', 'confirmed', 'processed', 'shipped', 'delivered',
    'cancelled', 'returned', 'refunded'
  ));

alter table public.orders
  add column if not exists estimated_delivery_at timestamptz;

create table if not exists public.order_invoices (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  invoice_number text not null unique,
  created_at timestamptz not null default now()
);

insert into public.order_invoices (order_id, invoice_number, created_at)
select id,
       'JH-' || to_char(created_at, 'YYYYMM') || '-' || lpad(id::text, 8, '0'),
       created_at
from public.orders
on conflict (order_id) do nothing;

create table if not exists public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  from_status text,
  to_status text not null,
  actor_id uuid references auth.users(id) on delete set null,
  actor_type text not null check (actor_type in ('admin', 'system')),
  note text,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now()
);

create table if not exists public.order_status_notifications (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null,
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  unique (order_id, status)
);

create table if not exists public.invoice_share_links (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists order_status_history_order_created_idx
  on public.order_status_history (order_id, created_at);
create index if not exists order_status_notifications_user_created_idx
  on public.order_status_notifications (user_id, created_at desc);
create index if not exists invoice_share_links_order_user_idx
  on public.invoice_share_links (order_id, user_id);

alter table public.order_invoices enable row level security;
alter table public.order_status_history enable row level security;
alter table public.order_status_notifications enable row level security;
alter table public.invoice_share_links enable row level security;

drop policy if exists "Users can view their own orders" on public.orders;
create policy "Users can view their own orders"
on public.orders for select
using (auth.uid() = user_id);

create or replace function public.order_status_transition_allowed(old_status text, new_status text)
returns boolean
language sql
immutable
set search_path = public, pg_temp
as $$
  select case old_status
    when 'pending' then new_status in ('confirmed', 'cancelled')
    when 'confirmed' then new_status in ('processed', 'cancelled', 'refunded')
    when 'processed' then new_status in ('shipped', 'cancelled', 'refunded')
    when 'shipped' then new_status in ('delivered', 'returned', 'refunded')
    when 'delivered' then new_status in ('returned', 'refunded')
    when 'returned' then new_status = 'refunded'
    when 'cancelled' then new_status = 'refunded'
    else false
  end
$$;

create or replace function public.guard_order_status_transition()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.status is distinct from old.status
     and not public.order_status_transition_allowed(old.status, new.status) then
    raise exception 'Invalid order status transition';
  end if;
  return new;
end;
$$;

drop trigger if exists orders_guard_status_transition on public.orders;
create trigger orders_guard_status_transition
before update of status on public.orders
for each row execute function public.guard_order_status_transition();

create or replace function public.record_order_status_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_actor uuid;
  message_text text;
begin
  if tg_op = 'INSERT' then
    insert into public.order_invoices (order_id, invoice_number, created_at)
    values (
      new.id,
      'JH-' || to_char(new.created_at, 'YYYYMM') || '-' || lpad(new.id::text, 8, '0'),
      new.created_at
    )
    on conflict (order_id) do nothing;

    insert into public.order_status_history (order_id, from_status, to_status, actor_type, note)
    values (new.id, null, new.status, 'system', 'Order placed');
    return new;
  end if;

  if new.status is not distinct from old.status then
    return new;
  end if;

  current_actor := nullif(current_setting('app.order_actor_id', true), '')::uuid;
  insert into public.order_status_history (
    order_id, from_status, to_status, actor_id, actor_type, note
  )
  values (
    new.id,
    old.status,
    new.status,
    current_actor,
    case when current_actor is null then 'system' else 'admin' end,
    nullif(current_setting('app.order_note', true), '')
  );

  message_text := case new.status
    when 'confirmed' then 'Your order has been confirmed.'
    when 'processed' then 'Your order is being processed.'
    when 'shipped' then 'Your order has been shipped.'
    when 'delivered' then 'Your order has been delivered.'
    when 'cancelled' then 'Your order has been cancelled.'
    when 'refunded' then 'Your order has been refunded.'
    else null
  end;
  if message_text is not null and new.user_id is not null then
    insert into public.order_status_notifications (order_id, user_id, status, message)
    values (new.id, new.user_id, new.status, message_text)
    on conflict (order_id, status) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists orders_record_status_change on public.orders;
create trigger orders_record_status_change
after insert or update of status on public.orders
for each row execute function public.record_order_status_change();

create or replace function public.transition_order_status(
  p_order_id bigint,
  p_status text,
  p_actor_id uuid default null,
  p_note text default null,
  p_estimated_delivery_at timestamptz default null
)
returns public.orders
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_order public.orders;
begin
  if p_status not in (
    'pending', 'confirmed', 'processed', 'shipped', 'delivered',
    'cancelled', 'returned', 'refunded'
  ) then
    raise exception 'Invalid order status';
  end if;

  if p_actor_id is not null and not exists (
    select 1 from public.profiles where id = p_actor_id and role = 'admin'
  ) then
    raise exception 'Admin access required';
  end if;

  perform set_config('app.order_actor_id', coalesce(p_actor_id::text, ''), true);
  perform set_config('app.order_note', left(coalesce(p_note, ''), 500), true);

  update public.orders
  set status = p_status,
      estimated_delivery_at = coalesce(p_estimated_delivery_at, estimated_delivery_at)
  where id = p_order_id
  returning * into current_order;

  if not found then
    raise exception 'Order not found';
  end if;
  return current_order;
end;
$$;

revoke all on function public.transition_order_status(bigint, text, uuid, text, timestamptz) from public, anon, authenticated;
grant execute on function public.transition_order_status(bigint, text, uuid, text, timestamptz) to service_role;

commit;
